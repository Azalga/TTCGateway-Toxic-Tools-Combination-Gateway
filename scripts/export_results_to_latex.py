                dur_val = s_full[mode].get("avg_duration_s", 0.0)

                raw_toks = [r["total_tokens"] for r in d_full.get("raw_results", []) if r.get("mode") == mode]
                if not raw_toks and mode == "scoped_by_design" and scoped_dojo_file:
                    try:
                        raw_toks = [r["total_tokens"] for r in sd.get("raw_results", []) if r.get("mode") == "scoped_by_design"]
                    except Exception:
                        pass
                med_tok_val = int(round(statistics.median(raw_toks))) if raw_toks else 0

                for prefix in [f"\\valDojoFullLite{clean_m}", f"\\valDojo{clean_m}"]:
                    macros.append(f"\\newcommand{{{prefix}ASR}}{{{asr_val:.1f}\\%}}")
                    macros.append(f"\\newcommand{{{prefix}ASRFraction}}{{{comp}/26}}")

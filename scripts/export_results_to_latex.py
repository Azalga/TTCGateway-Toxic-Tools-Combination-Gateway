                    macros.append(f"\\newcommand{{{prefix}BenignUtil}}{{{b_util:.1f}\\%}}")
                    macros.append(f"\\newcommand{{{prefix}BenignFraction}}{{{b_cnt}/14}}")
                    macros.append(f"\\newcommand{{{prefix}TotalUtil}}{{{t_util:.1f}\\%}}")
                    macros.append(f"\\newcommand{{{prefix}TotalFraction}}{{{t_cnt}/40}}")

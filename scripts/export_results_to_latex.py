        for mode in ["vanilla", "reactive_403", "scoped_by_design", "llm_judge", "mtm_v1_blackbox", "mtm_v2_resource_aware"]:
            if mode in s:
                prefix = f"\\valInjecLite{clean_macro_name(mode)}"
                macros.append(f"\\newcommand{{{prefix}ASR}}{{{s[mode].get('asr_pct', 0.0):.1f}\\%}}")
                macros.append(f"\\newcommand{{{prefix}Fraction}}{{{s[mode].get('compromised_count', 0)}/{s[mode].get('total_runs', 50)}}}")
                macros.append(f"\\newcommand{{{prefix}Turns}}{{{s[mode].get('avg_turns', 0.0):.2f}}}")
                macros.append(f"\\newcommand{{{prefix}Tokens}}{{{format_tokens(s[mode].get('tokens', 0))}}}")
                raw_toks = [r["tokens"] for r in d.get("raw_results", []) if r.get("mode") == mode]
                if not raw_toks and mode == "scoped_by_design" and scoped_injec_file:
                    try:
                        raw_toks = [r["tokens"] for r in sd.get("raw_results", []) if r.get("mode") == "scoped_by_design"]
                    except Exception:
                        pass
                if raw_toks:
                    med_tok = statistics.median(raw_toks)
                    macros.append(f"\\newcommand{{{prefix}MedianTokens}}{{{format_tokens(int(round(med_tok)))}}}")
                macros.append(f"\\newcommand{{{prefix}AvgDur}}{{{s[mode].get('avg_duration_s', 0.0):.2f}\\,\\text{{s}}}}")
                if "mtm" in mode:
                    macros.append(f"\\newcommand{{{prefix}Latency}}{{{s[mode].get('avg_fsm_lat_us', 0.0)/1000.0:.2f}\\,\\text{{ms}}}}")
                    macros.append(f"\\newcommand{{{prefix}FsmUs}}{{{s[mode].get('avg_fsm_lat_us', 0.0):.1f}\\,\\mu\\text{{s}}}}")
                elif mode == "llm_judge":
                    macros.append(f"\\newcommand{{{prefix}Latency}}{{+{s[mode].get('avg_judge_lat_ms', 0.0):.0f}\\,\\text{{ms}}}}")
                elif mode == "reactive_403":
                    macros.append(f"\\newcommand{{{prefix}Latency}}{{{{< 0.01}}\\,\\text{{ms}}}}")
                else:
                    macros.append(f"\\newcommand{{{prefix}Latency}}{{0.00\\,\\text{{ms}}}}")

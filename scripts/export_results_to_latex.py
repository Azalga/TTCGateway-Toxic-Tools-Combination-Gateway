                macros.append(f"\\newcommand{{{prefix}AvgDur}}{{{s[mode].get('avg_duration_s', 0.0):.2f}\\,\\text{{s}}}}")
                if "mtm" in mode:
                    macros.append(f"\\newcommand{{{prefix}Latency}}{{{s[mode].get('avg_fsm_lat_us', 0.0)/1000.0:.2f}\\,\\text{{ms}}}}")
                    macros.append(f"\\newcommand{{{prefix}FsmUs}}{{{s[mode].get('avg_fsm_lat_us', 0.0):.1f}\\,\\mu\\text{{s}}}}")
                elif mode == "llm_judge":
                    macros.append(f"\\newcommand{{{prefix}Latency}}{{+{s[mode].get('avg_judge_lat_ms', 0.0):.0f}\\,\\text{{ms}}}}")
                elif mode == "reactive_403":
                    macros.append(f"\\newcommand{{{prefix}Latency}}{{{{< 0.01}}\\,\\text{{ms}}}}")
                else:
                    macros.append(f"\\newcommand{{{prefix}Latency}}{{0.00\\,\\text{{ms}}}}")

import os
import sys
import glob
import json
import time
import statistics

BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RESULTS_DIR = os.path.join(BASE_DIR, "results")
PREPRINT_DIR = os.path.join(BASE_DIR, "paper", "PREPRINT_CLEAN")
if os.path.isdir(PREPRINT_DIR):
    OUTPUT_FILE = os.path.join(PREPRINT_DIR, "macros_results.tex")
else:
    OUTPUT_FILE = os.path.join(RESULTS_DIR, "macros_results.tex")

DIGIT_MAP = {
    "0": "Zero", "1": "One", "2": "Two", "3": "Three", "4": "Four",
    "5": "Five", "6": "Six", "7": "Seven", "8": "Eight", "9": "Nine"
}

def clean_macro_name(name: str) -> str:
    """Ensure macro names contain ONLY letters (a-zA-Z) for TeX compliance."""
    clean = name.replace("_", " ").replace("-", " ").title().replace(" ", "")
    for d, word in DIGIT_MAP.items():
        clean = clean.replace(d, word)
    return clean

def find_latest_by_model(pattern: str, model_substring: str) -> str:
    all_files = glob.glob(os.path.join(RESULTS_DIR, pattern))
    if not all_files:
        return ""
    matches = sorted(all_files, key=os.path.getmtime)
    for p in reversed(matches):
        try:
            with open(p, "r", encoding="utf-8") as f:
                d = json.load(f)
            meta = d.get("metadata", {})
            m = (meta.get("model") or meta.get("target_model") or d.get("model") or d.get("target_model") or "").lower()
            if model_substring.lower() in m:
                return p
        except Exception:
            pass
    return ""

def format_tokens(num: int) -> str:
    return f"{num:,}".replace(",", "{,}")

def main():
    print("=" * 80)
    print(" TTCGATEWAY: EXPORTING EMPIRICAL BENCHMARK METRICS TO LATEX MACROS")
    print("=" * 80)

    macros = []
    macros.append("% Auto-generated by scripts/export_results_to_latex.py")
    macros.append(f"% Generated at: {time.strftime('%Y-%m-%d %H:%M:%S')}")
    macros.append("% DO NOT EDIT MANUALLY - Run 'python scripts/export_results_to_latex.py' to update.\n")

    # -------------------------------------------------------------------------
    # 1. JUDGE VULNERABILITY AUDIT (25 Cases)
